# -*- coding: utf-8 -*-
"""Единая точка отсчёта времени для всех генераторов Пульса.

Завод живёт в Алматы (UTC+5), а GitHub Actions — в UTC. Раньше каждый скрипт брал
date.today() / datetime.now(), то есть время раннера. С 00:00 до 05:00 по Алматы это
ещё вчерашняя дата по UTC: страницы писали «обновлено вчера», а «последний полный день»
съезжал на сутки назад и терял день данных. Дневные крон-запуски (08/14/18/20 по Алматы)
в это окно не попадали, поэтому вживую не проявлялось — но ломалось на любом ручном
запуске ночью и сломалось бы от смены расписания.

Дата и время берутся здесь и только здесь.
"""
import datetime as _dt

TZ = _dt.timezone(_dt.timedelta(hours=5))


def now():
    """Текущий момент по Алматы. Naive — чтобы strftime вёл себя ровно как раньше."""
    return _dt.datetime.now(TZ).replace(tzinfo=None)


def today():
    """Сегодняшняя дата по Алматы."""
    return now().date()
