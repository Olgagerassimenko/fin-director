# -*- coding: utf-8 -*-
"""
gen_baza_seed.py — заготовка единой базы компании.

Смысл. База компании не заполняется с чистого листа: половина объектов уже
описана в айко и в сервисах ERP. Этот сборщик вынимает оттуда всё, что можно
узнать машинно — юрлица, склады, счета учёта, людей, системы, процессы — и
кладёт готовыми карточками. Человеку остаётся дописать то, чего ни в одной
системе нет: кто владелец, где договор, какой регламент.

Заготовка не хранит правок: всё, что вписали руками, живёт в воркере и
перекрывает карточку по идентификатору. Поэтому сборщик можно гонять заново
сколько угодно — он ничего не затрёт.
"""
import io, os, json, re, sys, datetime
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
try:
    import almaty                      # время завода, а не раннера
    NOW = almaty.now()
except Exception:
    NOW = datetime.datetime.now()

HERE = os.path.dirname(os.path.abspath(__file__))
OUT = os.path.join(HERE, "baza_seed.js")


def load_js(path, var):
    s = io.open(path, encoding="utf-8").read()
    return json.loads(s.split("=", 1)[1].rstrip().rstrip(";\n").rstrip(";"))


def main(aika_path, upak_path):
    A = load_js(aika_path, "AIKA")
    U = load_js(upak_path, "UPAK")
    rows = []

    seen = set()

    def add(t, i, n, **kw):
        i = i or "x"
        base, k = i, 2
        while t + ":" + i in seen:        # два счёта без кода могут дать один ключ
            i = "%s-%d" % (base, k); k += 1
        seen.add(t + ":" + i)
        r = {"id": t + ":" + i, "t": t, "n": n}
        r.update({k: v for k, v in kw.items() if v not in (None, "", [], {})})
        rows.append(r)

    # ── 1. юрлица ───────────────────────────────────────────────────────
    add("ur", "fz", "Фуд Завод", code="ФЗ", src="ERP · CRM",
        note="Основное юрлицо. В служебных записках процессы с приставкой «ФЗ».",
        need=["БИН", "система налогообложения", "директор", "банки"])
    add("ur", "fza", "Фуд Завод Астана", code="ФЗА", src="ERP · CRM",
        note="Второе юрлицо: в CRM есть отдельные процессы «ФЗА».",
        need=["БИН", "система налогообложения", "директор", "связь со складом Астаны"])

    # ── 2. склады и точки (из айко) ─────────────────────────────────────
    for a in A.get("accounts", []):
        if a.get("so") != "STORE":
            continue
        add("obj", re.sub(r"[^a-z0-9а-я]+", "-", a["name"].lower()).strip("-"),
            a["name"], code=a.get("code"), src="iiko · склад",
            note="Склад из айко. Остатки и движение видны в «Упаковке» и «Складах» на Пульсе.",
            need=["адрес", "материально ответственный", "юрлицо"])

    # ── 3. счета учёта (из айко) ────────────────────────────────────────
    GRU = {"ASSETS": "Активы", "LIABILITIES": "Обязательства",
           "EQUITY": "Капитал", "INCOME_EXPENSES": "Доходы и расходы"}
    for a in A.get("accounts", []):
        if a.get("so") == "STORE":
            continue
        tag = [GRU.get(a.get("grp"), a.get("grp") or "")]
        if a.get("cf") == 1:
            tag.append("денежный")
        add("acc", re.sub(r"[^a-z0-9а-я]+", "-", (a.get("code") or a["name"]).lower()).strip("-"),
            a["name"], code=a.get("code"), src="iiko · план счетов",
            tags=[x for x in tag if x],
            note=("Денежный счёт: участвует в ДДС." if a.get("cf") == 1 else ""),
            need=["кто отвечает за счёт"])

    # ── 4. люди (кто реально работает в айко) ───────────────────────────
    who = {}
    for e in A.get("events", []):
        u = (e.get("u") or "").strip()
        if u:
            who[u] = who.get(u, 0) + 1
    for u, n in sorted(who.items(), key=lambda kv: -kv[1]):
        add("people", re.sub(r"[^a-zа-я0-9]+", "-", u.lower()).strip("-"), u,
            src="iiko · журнал действий",
            note="Работает в айко: действий за время наблюдения — %d." % n,
            need=["должность", "подразделение", "телефон", "какие системы нужны"])

    # ── 5. системы и доступы ────────────────────────────────────────────
    SYS = [
        ("portal", "Портал ERP", "https://portal.erp-system-fz.kz/",
         "Единый вход во все сервисы платформы. Через него же смена пароля и выход отовсюду."),
        ("zavod", "Завод (ERP)", "https://zavod.erp-system-fz.kz/",
         "Производство, склад, продажи, служебные записки, задачи и документы."),
        ("hr", "HR", "https://hr.erp-system-fz.kz/",
         "Кадры: сотрудники, табели, касса и расчёт зарплаты."),
        ("catalog", "Каталог", "https://catalog.erp-system-fz.kz/",
         "Продукция завода из айко, прайсы и контрагенты."),
        ("pulse", "Пульс", "index.html",
         "Финансовая аналитика: ДДС, ОПиУ, продажи, закуп, себестоимость, упаковка, контроль закрытого периода."),
        ("iiko", "iiko", "https://fudzavod.iiko.it/",
         "Учётная система завода: склады, себестоимость, продажи, проводки. Первоисточник почти всех цифр."),
        ("1c", "1С — бухгалтерская база", "",
         "Бухгалтерия: налоги, реализация по юрлицам, основные средства, договоры. На Пульсе из неё живут "
         "разделы «Налоги» и «Реализация». Платформа ERP построена на этой базе."),
        ("bitrix", "Битрикс24", "",
         "Оплаты и заявки: из неё собирается отчёт по оплатам на Пульсе."),
    ]
    for i, n, link, note in SYS:
        add("sys", i, n, link=link, src="платформа", note=note,
            need=["кто администратор", "у кого есть доступ", "где хранится пароль"])

    # ── 6. процессы CRM ─────────────────────────────────────────────────
    for i, n in (("akt-prorabotki", "Акт проработки сырья"),
                 ("soglasovanie-dogovora-fz", "Согласование договора (ФЗ)"),
                 ("soglasovanie-dogovora-fza", "Согласование договора (ФЗА)")):
        add("proc", i, n, src="ERP · CRM · служебные записки",
            link="https://zavod.erp-system-fz.kz/crm/memos/new/",
            note="Процесс служебной записки. Исполненные файлы сами падают в раздел «Документы».",
            need=["кто запускает", "кто согласует", "срок", "что считается исполнением"])

    # ── 7. показатели: где какая цифра живёт ────────────────────────────
    KPI = [
        ("dengi", "Деньги на счетах и в кассах", "дашборд_ддс_прямой.html", "iiko · денежные счета",
         "Остаток и движение по 22 денежным счетам. Контроль закрытого периода — в «Айке»."),
        ("vyruchka", "Выручка", "продажи_2026.html", "iiko · расходные накладные",
         "Продажи Фуд Завода по контрагентам и месяцам. Olive считается отдельно."),
        ("sebes", "Себестоимость", "себестоимость_маржа.html", "iiko · техкарты и склад",
         "Плывёт задним числом при правке техкарт — см. правило контроля в «Айке»."),
        ("dzkz", "Дебиторка и кредиторка", "дз_кз.html", "iiko · счёт 3.06 и ДЗ",
         "Кто кому должен, по контрагентам и неделям."),
        ("opiu", "Прибыль", "опиу_2026.html", "iiko · проводки",
         "Отчёт о прибылях и убытках по месяцам."),
        ("zakup", "Закуп", "закуп.html", "iiko · приходные накладные",
         "Что закупили, у кого и почём, в том числе с рынка."),
        ("upak", "Упаковка", "упаковка.html", "iiko · склад несъедобного",
         "Остатки, неснижаемый запас и заявка поставщикам. Этикетки — отдельным разделом."),
        ("zp", "Фонд оплаты труда", "зарплата.html", "HR · табели и расчёт",
         "Расчёт по сотруднику и ФОТ. Закрытый раздел со своим паролем."),
        ("nalogi", "Налоги", "калькулятор.html", "расчёт по ставкам РК",
         "Ставки 2026 года, сроки уплаты и календарь платежей."),
        ("kontrol", "Контроль закрытого периода", "айка.html", "iiko · сверка каждые 3 часа",
         "Правила, отклонения и журнал действий в айко: кто что менял задним числом."),
    ]
    for i, n, link, src, note in KPI:
        add("kpi", i, n, link=link, src=src, note=note,
            need=["кто отвечает за цифру", "как часто смотрим", "что считается нормой"])

    # ── 8. где чья правда: разводим системы, чтобы не плодить дубли ─────
    TRUTH = [
        ("nomen", "Номенклатура и техкарты", "iiko",
         "Блюда, полуфабрикаты, сырьё, упаковка и состав карт. Каталог показывает их наружу, "
         "база только ссылается."),
        ("sklad", "Остатки и движение склада", "iiko",
         "Приход, расход, инвентаризация, себестоимость партий."),
        ("prodazhi", "Отгрузки и выручка", "iiko",
         "Расходные накладные по контрагентам. В 1С те же суммы попадают как реализация — сверка "
         "живёт в разделе «Реализация» на Пульсе."),
        ("buh", "Бухгалтерия и налоги", "1С",
         "Начисления и уплата налогов, основные средства, отчётность. Айко этого не знает."),
        ("kadry", "Кадры, табели, зарплата", "HR (платформа)",
         "Сотрудники, графики, расчёт. Пульс берёт отсюда ФОТ."),
        ("ceny", "Прайсы и контрагенты", "Каталог (платформа)",
         "Отпускные цены и карточки контрагентов для продаж."),
        ("process", "Согласования и поручения", "Завод · CRM (платформа)",
         "Служебные записки, задачи, исполненные документы."),
        ("oplaty", "Заявки на оплату", "Битрикс24",
         "Кто что просит оплатить и в каком статусе."),
        ("analitika", "Аналитика и контроль", "Пульс",
         "Ничего не хранит как первоисточник: считает из айко, 1С, HR и Каталога."),
    ]
    for i, n, src, note in TRUTH:
        add("truth", i, n, src=src, note=note,
            need=["кто отвечает за эти данные", "как часто сверяем с другими системами"])

    # ── 9. пустые разделы — с подсказкой, что сюда вписывать ────────────
    data = {
        "updated": NOW.strftime("%d.%m.%Y %H:%M"),
        "rows": rows,
    }
    io.open(OUT, "w", encoding="utf-8").write(
        "window.BAZA_SEED=" + json.dumps(data, ensure_ascii=False, separators=(",", ":")) + ";\n")
    byt = {}
    for r in rows:
        byt[r["t"]] = byt.get(r["t"], 0) + 1
    print("карточек:", len(rows), byt)
    print("записан", OUT, os.path.getsize(OUT), "байт")


if __name__ == "__main__":
    main(sys.argv[1], sys.argv[2])
